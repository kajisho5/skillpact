"""Export the pre-install decision of (contract x harness policy) to runtime policy formats.
- hushspec: HushSpec 1.0 document (YAML). Verified against the HushSpec core spec field tables (strict: only known fields).
- rego: an OPA/Rego module (package skillpact.<skill>) usable as the policy behind APS or ACS, which both
  accept Rego; the APS/ACS manifest wiring itself is not generated (their manifest formats are not yet verified here)."""
from __future__ import annotations
import json, re
import yaml
from .core import match_policy, expand_scope

HUSH_RULES = {"forbidden_paths", "path_allowlist", "egress", "secret_patterns", "patch_integrity", "shell_commands", "tool_access",
              "computer_use", "remote_desktop_channels", "input_injection", "browser_automation", "code_execution"}


def _tools(contract, m):
    by = {c["capability"]: c["decision"] for c in m["capabilities"]}
    out = {"allow": [], "ask": [], "deny": []}
    for cap in contract["capabilities"]:
        t = cap.get("entry", {}).get("mcp_tool")
        if t: out["deny" if m["decision"] == "deny" and not m["capabilities"] else by.get(cap["id"], "deny")].append(t)
    return out


def hushspec(contract, policy) -> dict:
    m = match_policy(contract, policy); t = _tools(contract, m); p = contract["permissions"]
    allowed_hosts = [] if m["decision"] == "deny" else [h for h in expand_scope(p["network"].get("scope", [])) if p["network"]["level"] == "scoped" and any(
        e["effect"] == "network" and e["decision"] == "allow" for c in m["capabilities"] for e in c["effects"] + [{"effect": x["effect"], "decision": x["decision"]} for x in c.get("conditional", [])])]
    doc = {"hushspec": "1.0.0", "name": f"{contract['skill']['name']}-{contract['skill']['version']}",
           "description": "Generated by skillpact export from a skill contract and a harness policy. $VARS must be substituted by the host.",
           "rules": {
               "tool_access": {"enabled": True, "allow": t["allow"], "require_confirmation": t["ask"], "block": t["deny"], "default": "block"},
               "egress": {"enabled": True, "allow": [h.replace("*.", "**.") for h in allowed_hosts], "default": "block"},
               "forbidden_paths": {"enabled": True, "patterns": ["**/.env", "**/.ssh/**", "**/*.pem"]},
           }}
    if p["write"]["level"] == "scoped" or p["read"]["level"] == "scoped":
        doc["rules"]["path_allowlist"] = {"enabled": True, "read": p["read"].get("scope", []), "write": p["write"].get("scope", [])}
    assert set(doc["rules"]) <= HUSH_RULES
    return doc


def rego(contract, policy) -> str:
    m = match_policy(contract, policy); t = _tools(contract, m)
    pkg = re.sub(r"[^a-z0-9_]", "_", contract["skill"]["name"].lower())
    j = lambda xs: json.dumps(sorted(xs))
    return f"""package skillpact.{pkg}

# Generated by skillpact export. input: {{"tool_name": "<mcp tool>"}}
# decision is one of "allow" | "ask" | "deny"; map "ask" to APS audit+deny-until-approved or ACS "escalate".

import rego.v1

allow_tools := {j(t['allow'])}
ask_tools := {j(t['ask'])}
deny_tools := {j(t['deny'])}

default decision := "deny"

decision := "allow" if input.tool_name in allow_tools
decision := "ask" if input.tool_name in ask_tools
"""


def export(contract, policy, fmt):
    if fmt == "hushspec": return yaml.safe_dump(hushspec(contract, policy), sort_keys=False)
    if fmt in ("aps", "acs", "rego"): return rego(contract, policy)
    raise ValueError(fmt)
